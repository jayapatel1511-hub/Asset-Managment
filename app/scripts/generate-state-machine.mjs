#!/usr/bin/env node
/**
 * Generates packages/contracts/src/stateMachine.ts from data/reference/state_machine.json.
 *
 * Constitution Principle VI / docs/02-app.md: "domain/stateMachine.ts must export the matrix
 * as data (not code) so the same JSON can be pasted into the flow's Compose action — one
 * definition, two consumers." This script is that single generation step: the JSON file is the
 * one definition; this file and solution/flows/F1/definition.json are its two consumers. Never
 * hand-edit app/src/domain/stateMachine.ts — edit the JSON instead. Wired as predev/prebuild in
 * package.json so `npm run dev` and `npm run build` always regenerate it first;
 * `npm run generate:state-machine` also runs it standalone.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(__dirname, "../../data/reference/state_machine.json");
const TARGET = path.resolve(__dirname, "../../packages/contracts/src/stateMachine.ts");

const raw = readFileSync(SOURCE, "utf-8");
const data = JSON.parse(raw);

const statuses = data.statuses;
const transitions = data.transitions;

// validate shape before generating — fail loudly rather than emit something broken
for (const status of Object.keys(transitions)) {
  if (!statuses.includes(status)) {
    throw new Error(`state_machine.json: transitions has unknown source status ${status}`);
  }
  for (const [txnType, toStatus] of Object.entries(transitions[status])) {
    if (!statuses.includes(toStatus)) {
      throw new Error(
        `state_machine.json: ${status} --${txnType}--> unknown status ${toStatus}`
      );
    }
  }
}

const banner = `/**
 * GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Source of truth: data/reference/state_machine.json
 * Generated by:    app/scripts/generate-state-machine.mjs (\`npm run generate:state-machine\`)
 *
 * Constitution Principle V (invalid transitions refused at every layer) and Principle VI (one
 * definition, two consumers): this is the app's copy of the transition matrix. The other
 * consumer is solution/flows/F1/definition.json, which is built from the same JSON so the two
 * can never drift — see solution/flows/F1/README.md for how it stays in step.
 *
 * Regenerate after editing the JSON: \`npm run generate:state-machine\`.
 */

export type AssetStatus = ${statuses.map((s) => JSON.stringify(s)).join(" | ")};

export type TransactionType =
${[...new Set(Object.values(transitions).flatMap((t) => Object.keys(t)))]
  .sort()
  .map((t) => `  | ${JSON.stringify(t)}`)
  .join("\n")};

export const STATUSES: readonly AssetStatus[] = ${JSON.stringify(statuses, null, 2)} as const;

/** rows = current status, keys = transaction type, value = resulting status. Missing key = not allowed. */
export const STATE_MACHINE: Readonly<
  Record<AssetStatus, Partial<Record<TransactionType, AssetStatus>>>
> = ${JSON.stringify(transitions, null, 2)} as const;
`;

writeFileSync(TARGET, banner, "utf-8");
console.log(`Generated ${path.relative(process.cwd(), TARGET)} from ${path.relative(process.cwd(), SOURCE)}`);
